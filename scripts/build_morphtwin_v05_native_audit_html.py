def _font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = (
        [r"C:\Windows\Fonts\msyhbd.ttc", r"C:\Windows\Fonts\simhei.ttf"]
        if bold
        else [r"C:\Windows\Fonts\msyh.ttc", r"C:\Windows\Fonts\Deng.ttf"]
    )
    for c in candidates:
        if Path(c).is_file():
            return ImageFont.truetype(c, size=size)
    return ImageFont.load_default()


def _b64_data_uri(path: Path, mime: str) -> str:
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def _render_native_pilot2_video(p2: dict[str, Any], out_mp4: Path) -> Path:
    """Render 960x540 H.264 MP4 directly from REAL native MuJoCo 4.0.1 & Newton 1.8.0 NPZ trajectories."""
    mat = p2["variant_engine_matrix"]
    cf_mj = next(r for r in p2["counterfactual_crush_records"] if r["provenance"]["engine_id"] == "mujoco4")
    panels_spec = [
        ("标准 (MuJoCo 4.0.1 原生)", mat["nominal"]["mujoco4"]),
        ("变软 2× (MuJoCo 4.0.1 原生)", mat["soften_2x"]["mujoco4"]),
        ("硅胶迁移 (MuJoCo 4.0.1 原生)", mat["transfer_silicone_boot"]["mujoco4"]),
        ("标准 (Newton 1.8.0 原生)", mat["nominal"]["newton18"]),
        ("变软 2× (Newton 1.8.0 原生)", mat["soften_2x"]["newton18"]),
        ("过力压溃反事实 (MuJoCo 原生)", cf_mj),
    ]

    loaded = []
    for title, rec in panels_spec:
        npz_p = Path(rec["provenance"]["npz_path"])
        with np.load(npz_p, allow_pickle=False) as z:
            pts = np.asarray(z["deformable_points"], dtype=np.float64)
            tac = np.asarray(z["tactile_normal_force_n"], dtype=np.float64)
            if tac.ndim > 1:
                tac = np.max(np.abs(tac), axis=1)
        loaded.append((title, rec, pts, tac))

    f_title = _font(20, bold=True)
    f_sub = _font(12, bold=False)
    f_card = _font(13, bold=True)
    f_small = _font(11, bold=False)
    f_badge = _font(12, bold=True)

    W, H = 960, 540
    n_out = 54
    frames: list[Image.Image] = []

    for fi in range(n_out):
        im = Image.new("RGB", (W, H), (11, 18, 32))
        draw = ImageDraw.Draw(im)
        draw.rectangle([0, 0, W, 62], fill=(15, 23, 42))
        draw.line([0, 62, W, 62], fill=(16, 185, 129), width=2)
        draw.text(
            (20, 10),
            "Pilot 2 真实原生仿真轨迹对比（直接读取 MuJoCo 4.0.1 / Newton 1.8.0 独立子进程 NPZ）",
            fill=(248, 250, 252),
            font=f_title,
        )
        draw.text(
            (20, 38),
            "每格均为独立操作系统子进程原生仿真输出（标明真实 OS PID、实测形变损伤 dmg 与峰值触觉力 fn）",
            fill=(148, 163, 184),
            font=f_sub,
        )

        cw, ch = 300, 212
        for idx, (title, rec, pts, tac) in enumerate(loaded):
            row, col = idx // 3, idx % 3
            x0, y0 = 20 + col * (cw + 10), 74 + row * (ch + 12)
            x1, y1 = x0 + cw, y0 + ch
            ok = bool(rec["intact_task_success"])
            border = (16, 185, 129) if ok else (239, 68, 68)
            draw.rounded_rectangle((x0, y0, x1, y1), radius=10, fill=(17, 24, 39), outline=border, width=2)

            s_idx = min(int(fi * (len(pts) - 1) / max(n_out - 1, 1)), len(pts) - 1)
            cur_p = pts[s_idx]
            cur_f = float(tac[min(s_idx, len(tac) - 1)]) if len(tac) else 0.0
            pid = rec["provenance"]["process_pid"]
            dmg = rec["damage_score"]

            draw.text((x0 + 10, y0 + 7), title, fill=(248, 250, 252), font=f_card)
            draw.text((x0 + 10, y0 + 25), f"PID={pid} | dmg={dmg:.4f} | t={s_idx}/{len(pts)-1}", fill=(148, 163, 184), font=f_small)

            # XZ projection viewport of REAL native simulated deformable vertices
            vx0, vy0, vx1, vy1 = x0 + 10, y0 + 44, x1 - 10, y0 + 160
            draw.rectangle((vx0, vy0, vx1, vy1), fill=(8, 13, 24), outline=(30, 41, 59))
            all_x = pts[:, :, 0]
            all_z = pts[:, :, 2]
            xmin, xmax = float(np.nanmin(all_x)) - 0.04, float(np.nanmax(all_x)) + 0.04
            zmin, zmax = float(np.nanmin(all_z)) - 0.02, float(np.nanmax(all_z)) + 0.04
            xr, zr = max(xmax - xmin, 0.25), max(zmax - zmin, 0.14)

            def _proj(xv: float, zv: float) -> tuple[float, float]:
                px = vx0 + 10 + (vx1 - vx0 - 20) * ((xv - xmin) / xr)
                py = vy1 - 10 - (vy1 - vy0 - 20) * ((zv - zmin) / zr)
                return px, py

            # COM trail
            coms = np.nanmean(pts[: s_idx + 1], axis=1)
            trail = [_proj(float(c[0]), float(c[2])) for c in coms[:: max(1, len(coms) // 35)]]
            if len(trail) >= 2:
                draw.line(trail, fill=(56, 189, 248) if ok else (248, 113, 113), width=2)

            # Actual simulated deformable vertices cloud
            pcol = (52, 211, 153) if ok else (239, 68, 68)
            for v in cur_p:
                if np.all(np.isfinite(v)):
                    px, py = _proj(float(v[0]), float(v[2]))
                    draw.ellipse((px - 2.2, py - 2.2, px + 2.2, py + 2.2), fill=pcol)

            draw.text((x0 + 10, y0 + 166), f"实时触觉力: {cur_f:.2f} N (上限 14.0 N)", fill=(226, 232, 240), font=f_small)
            bar_r = min(cur_f / 20.0, 1.0)
            draw.rectangle((x0 + 10, y0 + 186, x0 + 170, y0 + 198), fill=(30, 41, 59))
            draw.rectangle(
                (x0 + 10, y0 + 186, x0 + 10 + int(160 * bar_r), y0 + 198),
                fill=(52, 211, 153) if cur_f <= 14.0 else (239, 68, 68),
            )
            draw.text((x0 + 180, y0 + 183), "PASS 原生通过" if ok else "FAIL 红牌拦截", fill=pcol, font=f_badge)

        draw.rectangle([20, 522, W - 20, 533], fill=(30, 41, 59))
        draw.rectangle([20, 522, 20 + int((W - 40) * (fi + 1) / n_out), 533], fill=(56, 189, 248))
        frames.append(im)

    out_mp4.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg", "-y", "-f", "rawvideo", "-vcodec", "rawvideo", "-pix_fmt", "rgb24",
        "-s", f"{W}x{H}", "-r", "16", "-i", "-", "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-preset", "medium", "-crf", "22", "-movflags", "+faststart", str(out_mp4),
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    assert proc.stdin is not None
    for fr in frames:
        proc.stdin.write(fr.tobytes())
    proc.stdin.close()
    _, err = proc.communicate(timeout=120)
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg error: {err.decode('utf-8', errors='ignore')}")
    return out_mp4


